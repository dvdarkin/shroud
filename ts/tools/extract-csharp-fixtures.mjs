// Regenerates test/integration/fixtures/*.ts from the C# fixture classes, so the TS
// tests run on exactly the same text as the C# tests.
//
//   node tools/extract-csharp-fixtures.mjs
//
// C# raw string literals ("""...""") drop the opening and closing delimiter lines and
// remove the closing delimiter's indentation from every line. Line breaks inside are
// the source file's (CRLF in a Windows checkout, LF elsewhere); the generated TS
// fixtures use LF. The differential tests exercise both variants.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../../src/Shroud.Tests.Integration/Fixtures/', import.meta.url);
const outDir = new URL('../test/integration/fixtures/', import.meta.url);

export function parseRawStringConstants(source) {
  const text = source.replace(/\r\n/g, '\n');
  const re = /public const string (\w+) = """\n([\s\S]*?)\n([ \t]*)""";/g;
  const result = [];
  for (const m of text.matchAll(re)) {
    const [, name, body, indent] = m;
    const lines = body.split('\n').map((line) => {
      if (line.trim() === '') return '';
      if (!line.startsWith(indent)) throw new Error(`${name}: line not indented by closing delimiter: ${line}`);
      return line.slice(indent.length);
    });
    result.push({ name, value: lines.join('\n') });
  }
  return result;
}

const templateLiteral = (s) => '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';

const lowerFirst = (s) => s[0].toLowerCase() + s.slice(1);

for (const file of ['ScannerFixtures', 'FalsePositiveFixtures']) {
  const source = readFileSync(fileURLToPath(new URL(`${file}.cs`, root)), 'utf8');
  const constants = parseRawStringConstants(source);
  const body = constants
    .map(({ name, value }) => `export const ${lowerFirst(name)} = ${templateLiteral(value)};\n`)
    .join('\n');
  const header =
    `// GENERATED by tools/extract-csharp-fixtures.mjs from\n` +
    `// src/Shroud.Tests.Integration/Fixtures/${file}.cs - do not edit by hand.\n` +
    `// Values are obviously synthetic but structurally valid. No real addresses, keys or amounts.\n\n`;
  const kebab = file.replace(/Fixtures$/, '').replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
  const target = fileURLToPath(new URL(`${kebab}-fixtures.ts`, outDir));
  writeFileSync(target, header + body);
  console.log(`wrote ${target} (${constants.length} fixtures)`);
}
