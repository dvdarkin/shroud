// Regenerates src/internal/unicode-tables.ts from a classes.json produced by the
// .NET probe (tools/dotnet-probe, mode "classes"). The probe enumerates every
// UTF-16 code unit against the real .NET 8 Regex engine, so the tables below are
// ground truth for that runtime, not a reimplementation of Unicode rules.
//
//   dotnet run -c Release --project tools/dotnet-probe -- classes classes.json
//   node tools/generate-unicode-tables.mjs classes.json
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const input = process.argv[2];
if (!input) {
  console.error('usage: node tools/generate-unicode-tables.mjs <classes.json>');
  process.exit(1);
}
const data = JSON.parse(readFileSync(input, 'utf8'));

const fmt = (ranges) => {
  const pairs = ranges.map(([lo, hi]) => `[0x${hex(lo)}, 0x${hex(hi)}]`);
  const lines = [];
  for (let i = 0; i < pairs.length; i += 6) lines.push('  ' + pairs.slice(i, i + 6).join(', ') + ',');
  return lines.join('\n');
};
const hex = (n) => n.toString(16).toUpperCase().padStart(4, '0');

// Case equivalences beyond the plain ASCII upper/lower pair.
const extras = [];
for (const [code, ranges] of Object.entries(data.ci)) {
  const ch = String.fromCharCode(Number(code));
  const plain = new Set([ch, ch.toLowerCase(), ch.toUpperCase()].map((c) => c.charCodeAt(0)));
  for (const [lo, hi] of ranges) {
    for (let c = lo; c <= hi; c++) if (!plain.has(c)) extras.push([Number(code), c]);
  }
}

const boundaryExtra = [];
const word = new Set();
for (const [lo, hi] of data.word) for (let c = lo; c <= hi; c++) word.add(c);
for (const [lo, hi] of data.boundaryWord) for (let c = lo; c <= hi; c++) if (!word.has(c)) boundaryExtra.push(c);

// The translator maps \p{Nd} to DOTNET_DIGIT and the scanner's digit filter (char.IsDigit)
// uses the same table, so all three must be the same set in .NET.
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
if (!same(data.pNd, data.digit) || !same(data.isDigit, data.digit)) throw new Error('\\p{Nd}, \\d and char.IsDigit differ');
// The translator does not case-close \p{..} classes; .NET must agree for the class it is used in.
if (!same(data.metadataKeyGuard, data.metadataKeyGuardCi)) throw new Error('IgnoreCase changes [\\p{L}\\p{Nd}_\\-]');

const out = `// GENERATED by tools/generate-unicode-tables.mjs - do not edit by hand.
//
// Character classes extracted from the .NET 8 System.Text.RegularExpressions
// engine by enumerating all 65,536 UTF-16 code units (probe culture: ${data.culture}).
// .NET regex classes operate on UTF-16 code units, so these tables are BMP-only
// by construction; supplementary-plane characters are surrogate pairs and never
// match \\d, \\w or \\s in .NET.
//
// Ranges are inclusive [lo, hi] pairs of UTF-16 code units.

export type CodeUnitRanges = readonly (readonly [number, number])[];

/** .NET \\d (Unicode Nd, BMP). Also \\p{Nd} and char.IsDigit (verified equal by the generator). */
export const DOTNET_DIGIT: CodeUnitRanges = [
${fmt(data.digit)}
];

/** .NET \\p{L}: Lu, Ll, Lt, Lm, Lo (BMP, .NET 8 Unicode data). */
export const DOTNET_LETTER: CodeUnitRanges = [
${fmt(data.letter)}
];

/** .NET \\w: L, Mn, Nd, Pc (BMP, .NET 8 Unicode data). */
export const DOTNET_WORD: CodeUnitRanges = [
${fmt(data.word)}
];

/** Extra code units .NET treats as word characters for \\b only (ZWNJ, ZWJ). */
export const DOTNET_BOUNDARY_EXTRA: readonly number[] = [${boundaryExtra.map((c) => `0x${hex(c)}`).join(', ')}];

/** .NET \\s: [\\f\\n\\r\\t\\v\\x85\\p{Z}] (note: U+0085 included, U+FEFF excluded, unlike JS). */
export const DOTNET_SPACE: CodeUnitRanges = [
${fmt(data.space)}
];

/**
 * RegexOptions.IgnoreCase equivalences for ASCII pattern characters beyond the plain
 * upper/lower pair, as [patternChar, extraMatchingCodeUnit]. Observed under a
 * non-Turkish culture; .NET picks the table from CultureInfo.CurrentCulture.
 */
export const DOTNET_IGNORECASE_EXTRAS: readonly (readonly [number, number])[] = [
${extras.map(([a, b]) => `  [0x${hex(a)}, 0x${hex(b)}], // ${String.fromCharCode(a)}`).join('\n')}
];
`;

const target = fileURLToPath(new URL('../src/internal/unicode-tables.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${target}`);
